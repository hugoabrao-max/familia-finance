create or replace view public.v_tx with (security_invoker = on) as
 SELECT t.id,
    t.account_id,
    t.raw_transaction_id,
    t.source,
    t.source_ref,
    t.event_date,
    t.event_at,
    t.amount,
    t.currency,
    t.description,
    t.description_raw,
    t.provider_code,
    t.type,
    t.status,
    t.operation_type,
    t.payment_data,
    t.merchant,
    t.installment_number,
    t.installment_total,
    t.bill_closing_date,
    t.bill_forecast_date,
    t.balance_after,
    t.provider_category,
    t.is_deleted_at_source,
    t.created_at,
    t.updated_at,
    t.category_id,
    t.category_source,
    t.category_confidence,
    t.rule_id,
    t.review_status,
    t.card_last4,
    t.holder_name,
    t.competence_month,
    t.import_job_id,
    t.counterpart_name,
    t.reconciliation,
    a.subtype AS account_subtype,
    a.name AS account_name,
    c.name AS category_name,
    c.kind AS category_kind,
    COALESCE(p.id, c.id) AS group_id,
    COALESCE(p.name, c.name) AS group_name,
    COALESCE(t.competence_month, (date_trunc('month'::text, (t.event_date)::timestamp with time zone))::date) AS month
   FROM (((transactions t
     JOIN accounts a ON ((a.id = t.account_id)))
     LEFT JOIN categories c ON ((c.id = t.category_id)))
     LEFT JOIN categories p ON ((p.id = c.parent_id)))
  WHERE ((NOT t.is_deleted_at_source) AND (t.reconciliation IS DISTINCT FROM 'duplicate_suspect'::text));
